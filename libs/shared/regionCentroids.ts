const toLatLng = ([lat, lng]: [number, number]): LatLng => ({ lat, lng });

/** 시/군/구 중심 좌표. 시/군/구가 없거나 표에 없으면 시/도 중심, 시/도도 없으면 null. */
export function regionCentroid(sido: string | null | undefined, sigungu?: string | null): LatLng | null {
  if (!sido) return null;
  const entry = REGION_CENTROIDS[sido];
  if (!entry) return null;
  const point = sigungu ? entry.sigungu[sigungu] : undefined;
  return toLatLng(point ?? entry.center);
}

const EARTH_RADIUS_KM = 6371;
const rad = (deg: number) => (deg * Math.PI) / 180;

/** 두 좌표 사이 거리(km, 하버사인). */
export function haversineKm(a: LatLng, b: LatLng): number {
  const dLat = rad(b.lat - a.lat);
  const dLng = rad(b.lng - a.lng);
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(rad(a.lat)) * Math.cos(rad(b.lat)) * Math.sin(dLng / 2) ** 2;
  return 2 * EARTH_RADIUS_KM * Math.asin(Math.min(1, Math.sqrt(h)));
}
